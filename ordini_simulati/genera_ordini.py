st = lambda n, **k: ParagraphStyle(n, fontName=k.pop("f", "Helvetica"), fontSize=k.pop("s", 9), leading=k.pop("l", 11), **k)
S, SB, T = st("s"), st("b", f="Helvetica-Bold"), st("t", f="Helvetica-Bold", s=20, l=24)

def build(d):
    tot = sum(int(r[-1]) for r in d["rows"])
    def foot(c, doc):
        c.saveState(); c.setFont("Helvetica", 8)
        c.drawRightString(A4[0] - 15*mm, 10*mm, "Pagina %d" % doc.page); c.restoreState()
    doc = BaseDocTemplate(OUT + d["file"], pagesize=A4, leftMargin=15*mm, rightMargin=15*mm, topMargin=15*mm, bottomMargin=18*mm,
                          title="Ordine " + d["num"], author=d["forn"][0])
    doc.addPageTemplates([PageTemplate(id="p", frames=[Frame(15*mm, 18*mm, A4[0]-30*mm, A4[1]-33*mm, id="f", leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0)], onPage=foot)])
    box = lambda title, lines: Table([[Paragraph(title, SB)]] + [[Paragraph(l, S)] for l in lines], colWidths=[88*mm],
            style=[("BOX", (0,0), (-1,-1), .6, colors.black), ("LEFTPADDING",(0,0),(-1,-1),5), ("TOPPADDING",(0,0),(-1,-1),1.5), ("BOTTOMPADDING",(0,0),(-1,-1),1.5)])
    el = [Paragraph("ORDINE", T), Paragraph("N. %s del %s" % (d["num"], d["data"].replace(".", "/")), st("x", s=11, l=14)), Spacer(1, 6*mm)]
    top = Table([[box("Fornitore", d["forn"]), box("Cliente", CUST)]], colWidths=[93*mm, 93*mm], style=[("VALIGN",(0,0),(-1,-1),"TOP"), ("LEFTPADDING",(0,0),(-1,-1),0)])
    dst = d["dest"] + (["Data consegna richiesta: " + d["cons"].replace(".", "/")] if d["cons"] else [])
    mid = Table([[box("Luogo di consegna", dst), ""]], colWidths=[93*mm, 93*mm], style=[("VALIGN",(0,0),(-1,-1),"TOP"), ("LEFTPADDING",(0,0),(-1,-1),0)])
    el += [top, Spacer(1, 4*mm), mid, Spacer(1, 6*mm)]
    data = [[Paragraph(c, SB) for c in d["cols"]]]
    for r in d["rows"]:
        data.append([Paragraph(x, S) for x in r])
    right = len(d["cols"]) - 1
    t = Table(data, colWidths=[w*mm for w in d["widths"]], repeatRows=1)
    t.setStyle(TableStyle([("GRID",(0,0),(-1,-1),.4,colors.grey), ("BACKGROUND",(0,0),(-1,0),colors.lightgrey),
        ("VALIGN",(0,0),(-1,-1),"MIDDLE"), ("TOPPADDING",(0,0),(-1,-1),3), ("BOTTOMPADDING",(0,0),(-1,-1),3)]))
    el += [t, Spacer(1, 4*mm), Paragraph("Totale quantità: %d" % tot, SB)]
    doc.build(el)

for d in DOCS: build(d)
